package StackAndQueue.Lv2;

import java.util.*;
public class TransportBox {
    public static void main(String[] args) {

    }

    public int solution(int[] order) {
        int answer = 0;
        Stack<Integer> sub = new Stack<>();

        int currentBox = 1; // 메인 컨베이어 벨트에서 현재 나올 차례인 상자 번호

        // 기사님이 요구하는 주문 순서대로 하나씩 검사
        for (int o : order) {

            // 1. 내가 원하는 상자(o)가 나올 때까지 메인 벨트의 상자를 보조 벨트에 일단 다 넣기
            // (이미 메인 벨트가 지나갔다면 이 while문은 자연스럽게 작동하지 않음)
            while (currentBox <= o) {
                sub.push(currentBox);
                currentBox++;
            }

            // 2. 보조 벨트의 맨 위 상자가 기사님이 원하는 상자인지 확인
            if (!sub.isEmpty() && sub.peek() == o) {
                sub.pop(); // 맞다면 트럭에 싣기
                answer++;
            } else {
                // 3. 메인 벨트에서 다 꺼내봤고, 보조 벨트 맨 위도 아니라면 더 이상 실을 수 없음
                break;
            }
        }

        return answer;
    }
}

